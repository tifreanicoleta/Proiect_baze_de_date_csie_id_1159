--Sa se afiseze toate produsele impreuna cu informatiile furnizorilor lor

SELECT p.COD_PRODUS, p.PRODUCATOR, p.PRET, p.STOC,
       f.DENUMIRE AS FURNIZOR, f.LOCALITATE AS LOC_FURNIZOR
FROM PRODUSE_IT p
INNER JOIN FURNIZORI f ON p.COD_FURNIZOR = f.COD_FURNIZOR
ORDER BY p.PRET DESC;

--sa se afiseze afiseze numarul de produse si pretul mediu pentru fiecare producator in parte

SELECT PRODUCATOR, COUNT(*) AS NR_PRODUSE, AVG(PRET) AS PRET_MEDIU
FROM PRODUSE_IT
GROUP BY PRODUCATOR;

--	Sa se afiseze producatorii care au un stoc total de peste 20 de unitati cumulate

SELECT PRODUCATOR, SUM(STOC) AS STOC_TOTAL
FROM PRODUSE_IT
GROUP BY PRODUCATOR
HAVING SUM(STOC) > 20;

-- Sa se afiseze codul comenzii si data acesteia (zi-luna-an) filtrand doar comenzile din anul curent
SELECT COD_COMANDA, TO_CHAR(DATA_COMANDA, 'Day, DD Month YYYY') AS DATA_DETALIATA
FROM COMENZI
WHERE EXTRACT(YEAR FROM DATA_COMANDA) = EXTRACT(YEAR FROM SYSDATE);

-- 	Sa se afiseze primele 3 litere ale producatorului si denumirea compmaniei clientului (daca aceasta lipseste se va afisa ‘Persoana Fizica’)

SELECT SUBSTR(PRODUCATOR, 1, 3) AS COD_PROD, NVL(COMPANIE, 'Persoana Fizica') AS ENTITATE
FROM PRODUSE_IT, CLIENTI;

--	Sa se clasifice produsele in funcție de pret și sa se traduca codul de tip echipament.
SELECT PRODUCATOR, PRET,
       CASE WHEN PRET > 3000 THEN 'Premium' ELSE 'Standard' END AS CATEGORIE,
       DECODE(COD_TIP, 1, 'Laptop', 2, 'Monitor', 3, 'Periferic', 'Altul') AS TIP_ECHIPAMENT
FROM PRODUSE_IT;

