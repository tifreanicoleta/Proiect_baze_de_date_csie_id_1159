CREATE VIEW V_STOC_CRITIC AS 
SELECT PRODUCATOR, CARACTERISTICI, STOC FROM PRODUSE_IT WHERE STOC < 10;

CREATE INDEX IDX_PRODUCATOR ON PRODUSE_IT(PRODUCATOR);

--	Sa se afiseze toti clientii si data comenzii lor, incluzand clientii care nu au comandat nimic pana acum

SELECT c.NUME, com.DATA_COMANDA
FROM CLIENTI c
LEFT OUTER JOIN COMENZI com ON c.COD_CLIENT = com.COD_CLIENT;


--Sa se afiseze produsele cu evaluare stoc (critic, mediu, bun) si recomandare de aprovizionare


SELECT PRODUCATOR, CARACTERISTICI, STOC, PRET,
       CASE 
           WHEN STOC = 0 THEN 'STOC EPUIZAT'
           WHEN STOC < 10 THEN 'STOC CRITIC - Comanda urgenta'
           WHEN STOC BETWEEN 10 AND 20 THEN 'STOC MEDIU - Monitorizare'
           ELSE 'STOC SUFICIENT'
       END AS STATUS_STOC,
       CASE 
           WHEN STOC < 10 THEN PRET * 20
           WHEN STOC < 20 THEN PRET * 10
           ELSE 0
       END AS VALOARE_REAPROVIZIONARE
FROM PRODUSE_IT
ORDER BY STOC ASC;
