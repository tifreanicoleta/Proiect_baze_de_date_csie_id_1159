--Sa se afiseze produsele cu pretul intre 500 si 300 de lei si garantie mai mare sau egala cu 24 de luni

SELECT COD_PRODUS, PRODUCATOR, CARACTERISTICI, PRET, GARANTIE
FROM PRODUSE_IT
WHERE PRET BETWEEN 500 AND 3000
  AND GARANTIE >= 24
ORDER BY PRET DESC;

--	Sa se afiseze clientii din Bucuresti si Cluj-Napoca care nu au companie asociata si au nume care contine litera ‘i’

SELECT NUME, LOCALITATE, EMAIL, COMPANIE
FROM CLIENTI
WHERE COMPANIE IS NULL
  AND LOCALITATE IN ('Bucuresti', 'Cluj-Napoca')
