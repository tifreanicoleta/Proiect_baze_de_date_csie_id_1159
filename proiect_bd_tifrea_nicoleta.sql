COD_FURNIZOR NUMBER(5) PRIMARY KEY,
DENUMIRE VARCHAR2(60) NOT NULL, 
TELEFON VARCHAR2(15) UNIQUE NOT NULL,
ADRESA VARCHAR2(100) NOT NULL,
LOCALITATE VARCHAR2(40) NOT NULL);

--table clienti

CREATE TABLE CLIENTI (
COD_CLIENT NUMBER(5) PRIMARY KEY,
NUME VARCHAR2(30) NOT NULL,
COMPANIE VARCHAR2(30),
ADRESA VARCHAR2(100) NOT NULL,
LOCALITATE VARCHAR2(40) NOT NULL,
TELEFON VARCHAR2(15) UNIQUE NOT NULL,
EMAIL VARCHAR2(50) UNIQUE NOT NULL,
STATUS VARCHAR2(10) NOT NULL);

ALTER TABLE CLIENTI
ADD CONSTRAINT CK_CLIENTI_STATUS
CHECK (STATUS IN ('ACTIV','INACTIV'));

--produse it

CREATE TABLE PRODUSE_IT (
COD_PRODUS NUMBER(5) PRIMARY KEY,
COD_FURNIZOR NUMBER(5) NOT NULL,
PRODUCATOR VARCHAR2(20) NOT NULL,
GARANTIE NUMBER(2) NOT NULL, 
STOC NUMBER(4) NOT NULL,
CARACTERISTICI VARCHAR2(100) NOT NULL,
PRET DECIMAL(10,2) NOT NULL,
COD_TIP NUMBER(5) NOT NULL);

ALTER TABLE PRODUSE_IT
ADD CONSTRAINT CK_PRODUSE_PRET
CHECK (PRET > 0);

ALTER TABLE PRODUSE_IT
ADD CONSTRAINT CK_PRODUSE_STOC
CHECK (STOC >= 0);

ALTER TABLE PRODUSE_IT
ADD CONSTRAINT CK_PRODUSE_GARANTIE
CHECK (GARANTIE BETWEEN 0 AND 60);

ALTER TABLE PRODUSE_IT
ADD CONSTRAINT FK_PRODUSE_FURNIZOR
FOREIGN KEY (COD_FURNIZOR)
REFERENCES FURNIZORI (COD_FURNIZOR);

ALTER TABLE PRODUSE_IT
